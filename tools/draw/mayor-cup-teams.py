def crest(team):
    tid, ar, fr, accent, shape, emblem, em_y, ball_y, ball_r = team
    hi, soft = ACCENTS[accent]
    outline, keyline = shape(0), shape(19)

    out = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">',
        f'  <title>{fr} — {ar}</title>',
        '  <!-- GENERATED by tools/draw/mayor-cup-teams.py. Do not hand-edit. -->',
        '  <defs>',
        f'    <clipPath id="shield"><path d="{outline}"/></clipPath>',
        '  </defs>',
        path(outline, fill=FIELD),
        '  <g clip-path="url(#shield)">',
    ]
    body = [path(keyline, stroke=soft, width=4)]
    body += emblem(CX, em_y, soft, hi)
    body += football(CX, ball_y, ball_r, FIELD, soft)
    out += ["  " + e.strip() for e in body]
    out += [
        '  </g>',
        # the edge goes on last, so a clipped emblem stops against it cleanly
        path(outline, stroke=hi, width=14),
        '</svg>',
    ]
    return "\n".join(out) + "\n"


def main():
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    out = os.path.join(root, "logos", "src", "teams", EVENT)
    os.makedirs(out, exist_ok=True)
    for t in TEAMS:
        dst = os.path.join(out, f"{t[0]}.svg")
        # REFUSE to overwrite artwork this script did not write. The eight files
        # here were redrawn by hand after this generator produced the first
        # draft, and a generator that silently replaces the real artwork with
        # its own draft is a trap — the tree looks fine until someone runs it.
        if os.path.exists(dst) and MARK not in open(dst, encoding="utf-8").read():
            print(f"SKIP  {t[0]}.svg — hand-drawn, not generated by this script")
            continue
        with open(dst, "w", encoding="utf-8") as fh:
            fh.write(crest(t))
        print(f"wrote logos/src/teams/{EVENT}/{t[0]}.svg  ({t[1]})")


if __name__ == "__main__":
    main()
