#!/usr/bin/env python3
"""
Draws the eight Mayor's Cup team crests into logos/src/teams/mayor-cup-2026/.

    python3 tools/draw/mayor-cup-teams.py

FILED BY EDITION, not by club. The eight names are this year's entrants and the
next Mayor's Cup will not have the same eight — a club folds, two merge, a new
one enters — so a crest belongs to an edition the way a fixture does. Filing
them flat under teams/ would make next August's set either overwrite this one
or collide with it. EVENT below is the only thing to change for a new edition;
it matches the event id in brand/entities.yml so the two trees line up.

These are STANDALONE marks. A committee wears the mosque and an event carries
the association's endorsement; a team is a competitor, not the association
acting in a field, so it gets none of that — no symbol, no endorsement, no
wordmark bound by the engine. That is also why the colours are literal here
rather than var() bound: nothing downstream re-inks these, so a token that no
build resolves would be a lie. The VALUES still come from the palette, listed
once in PALETTE below, so the set stays in the family by construction.

The visual language is taken from the eight crests the U18 clubs made
themselves (resources/u18-team-*.webp): a shield with a bright metal edge, a
dark field, an emblem keyed to what the club's NAME MEANS, and a football. Six
of those eight are shields and two are medallions, so both shapes are kept.
What is not kept is how they were made — four are AI renders with a stadium or
a leather ball baked into the background, which is why they cannot be put on a
fixture card. These are flat vector on a transparent ground.

The emblem is the part that carries the club. Each is a reading of the name:

    الناجحين   the successful   a summit, and the star above it
    الشناقطة   of Chinguetti    the minaret of the old town, over an open book
    لبنان      Lebanon          the cedar
    الصادقين   the truthful     an eight-point star, true in every direction
    أفجار      the dawns        the sun coming up over two dune ridges
    الذهبيين   the golden       a sun disc inside a laurel
    البارين    the dutiful      two ears of wheat, what duty yields
    الحزام     the belt         the belt itself, worn across the shield

── two things that were wrong in the first pass, and why they are structural ──

EVERYTHING IS CLIPPED TO THE SHIELD. The belt is a band 380 units long crossed
over a shield 348 wide; unclipped it hangs off both edges as a plank. Clipping
is not a safety net here, it is how a bend is drawn — the band is MEANT to run
edge to edge and stop at the outline. Every other emblem is clipped by the same
group, so no emblem can ever escape its crest no matter how it is retuned.

THE BALL IS FIVE SEAMS, NOT SIX PENTAGONS. logos/src/glyphs/football.svg is a
ring carrying six pentagons, and it is right at the size a glyph is used. Put
at r=50 inside a crest it stops being a ball: the five rim pentagons read as
separate blobs and the whole thing goes to a gear. What survives at crest scale
is the simplest true statement of a football — one pentagon at the centre and a
seam from each of its vertices to the rim. That is drawn here instead.
"""
