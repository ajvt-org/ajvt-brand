#!/usr/bin/env node
/**
 * Writes one guidelines page per mark, from the registry.
 *
 *   logos/guidelines/<entity>.md
 *
 * Generated, not written by hand. A guideline maintained separately from the
 * thing it describes is wrong within a month — it still says the accent is
 * copper after someone changed it to clinical, and the person reading it has no
 * way to know. Everything here is read out of brand/entities.yml and the token
 * files at build time, so it cannot disagree with what the build produced.
 *
 * The genuinely editorial prose — how to place a mark, what not to do — lives
 * once in templates/guidelines.md and is appended to every page.
 */
import { writeFileSync, readdirSync, existsSync, readFileSync, mkdirSync, rmSync } from 'node:fs'
import { p } from './lib/paths.mjs'
import { loadTokens } from './lib/tokens.mjs'
import { loadEntities } from './lib/entities.mjs'

const tokens = loadTokens()
const { entities } = loadEntities(tokens)
const min = tokens.space.logo['min-size']
const clear = tokens.space.logo['clear-space'].factor

const LAYOUT_USE = {
  symbol:     'The mark alone. Profile pictures, favicons, a stamp on a photograph — anywhere the name is already present.',
  roundel:    'The mark with the name set inside it. Use it where only one element fits and it must still say who we are.',
  'roundel-name': "The association's mark with this body's name set level beneath it, in the opening the arch leaves at the foot of the roundel. It reads as the association acting in a particular capacity, which is what an organ is — so use it on anything the body issues in its own right: a décision, a convocation, a stamped minute.",
  'roundel-motto': 'The historical logo in full: the mark, the name inside it, and the motto along the bottom of the arch. Use it on anything ceremonial — certificates, plaques, the cover of a décision. Not below 40 mm; the motto closes up.',
  horizontal: 'Letterheads, website headers, email signatures, banners. The default in any space wider than it is tall.',
  vertical:   'Cover pages, posters, roll-ups — anywhere with height to spare.',
  wordmark:   'The name alone. Only where the symbol already appears elsewhere on the same surface.',
  badge:      'The committee and event pattern. Social avatars, jerseys, stickers, event signage.',
  favicon:    'Browser tabs and app icons only. Detail is stripped; never use it at a large size.',
  seal:       'Official stamped documents only. This is not a logo.',
}
const VARIANT_USE = {
  color:        'The default. Use it wherever colour is available.',
  grayscale:    'One-colour printing that still reproduces tone: photocopies, newsprint, fax.',
  'mono-dark':  'A single ink on a light ground: stamps, engraving, embroidery, silk-screen.',
  'mono-light': 'Knocked out of a dark or photographic ground. Never place it on a light one.',
}

rmSync(p('logos/guidelines'), { recursive: true, force: true })
mkdirSync(p('logos/guidelines'), { recursive: true })
const shared = existsSync(p('templates/guidelines.md')) ? readFileSync(p('templates/guidelines.md'), 'utf8') : ''

const group = (files) => [
  `- **SVG** (${files.filter((f) => f.endsWith('.svg')).length}) — anything digital, and anything going to a print shop. Vector, and no font needs to be installed.`,
  `- **PNG** (${files.filter((f) => f.endsWith('.png')).length}) — transparent, at each size this mark is cleared for.`,
  `- **PDF** (${files.filter((f) => f.endsWith('.pdf')).length}) — hand these to a printer or an embroiderer.`,
].join('\n')

for (const e of entities) {
  const dir = p('logos/dist', e.dir)
  const built = existsSync(dir) ? readdirSync(dir) : []
  const a = e.accentColor
  const isBadge = e.layouts.includes('badge')

  const md = `<!-- GENERATED by tools/build-guidelines.mjs — do not edit.
     Change brand/entities.yml for this mark, or templates/guidelines.md for the
     shared prose, then run \`npm run build:guidelines\`. -->

# ${e.name.fr} — ${e.name.ar}
${e.notes ? `\n> ${e.notes.trim().replace(/\n\s*/g, '\n> ')}\n` : ''}
|  |  |
| --- | --- |
| Identifier | \`${e.id}\` |
| Kind | ${e.kind}${e.season ? ` · season ${e.season}` : ''} |
| Status | ${e.status ?? 'active'}${e.until ? ` · mandate ends ${String(e.until).slice(0, 10)}` : ''} |
| Arabic name | ${e.name.ar} |
| French name | ${e.name.fr} |
| Accent | \`${e.accent}\` — ${a.base} |
${e.mark ? `| Own artwork | \`logos/src/marks/${e.mark}.svg\` — colours in \`color.json\` → \`marks.${e.mark}\` |` : ''}
${e.ground ? `| Event ground | ${e.ground} |\n` : ''}| Generated files | \`logos/dist/${e.dir}/\` — ${built.length} |

## The wordmark

|  | Eyebrow | Name |
| --- | --- | --- |
| Arabic | ${e.wordmark.ar.eyebrow ?? '—'} | **${e.wordmark.ar.main}** |
| French | ${e.wordmark.fr?.eyebrow ?? '—'} | **${e.wordmark.fr?.main ?? '—'}** |

Set in **${tokens.fonts.arabic.wordmark.family}** for Arabic and **${tokens.fonts.latin.wordmark.family}** for French, and outlined to paths in every generated file — so a print shop without the font still gets the right letterforms. The wordmark is never retyped by hand and never set in another face. If it has to change, change \`brand/entities.yml\` and rebuild.

## Lockups

${e.layouts.map((l) => `### \`${l}\`\n\n${
  l === 'symbol' && e.mark ? `${e.name.fr}'s own artwork — \`logos/src/marks/${e.mark}.svg\`, not the association's mosque. An event runs for one season and is allowed a mark of its own; what keeps it in the family is the palette, which is drawn from the same mint and copper as everything else. Profile pictures, favicons, a stamp on a photograph.`
  : l === 'symbol' && e.glyph ? `The mark alone, with this mark's glyph set in the mosque's courtyard — the association's symbol carrying ${e.name.fr}'s. Profile pictures, favicons, a stamp on a photograph: anywhere the name is already present but the body still has to be identifiable.`
  : LAYOUT_USE[l] ?? ''}`).join('\n\n')}

## Colour variants

${e.variants.map((v) => `- **\`${v}\`** — ${VARIANT_USE[v]}`).join('\n')}

This mark's accent is \`${e.accent}\`: base \`${a.base}\`, soft \`${a.soft}\`, deep \`${a.deep}\`. ${
    e.kind === 'committee' || e.kind === 'event'
      ? 'The accent is the only thing that distinguishes this mark from its siblings — the symbol, the geometry and the typography are shared on purpose, so the family reads as one organisation.'
      : 'Statutory organs share the house accent. They are not sub-brands; they are the association acting in a particular capacity.'}

## Clear space

Leave at least **${(clear * 100).toFixed(0)}% of the symbol's diameter** empty on every side. Nothing enters it: no text, no image, no page edge, no second logo. The generated files already carry this margin, so a file placed flush against something still keeps the correct gap.

## Minimum size

| | Print | Screen |
| --- | --- | --- |
| ${isBadge ? 'Badge' : 'Symbol'} | ${isBadge ? min['badge-print-mm'] : min['symbol-print-mm']} mm | ${isBadge ? min['badge-screen-px'] : min['symbol-screen-px']} px |
| Horizontal lockup | ${min['horizontal-print-mm']} mm | ${min['horizontal-screen-px']} px |${
  e.layouts.includes('roundel-motto')
    ? `\n| Roundel with motto | ${min['roundel-motto-print-mm']} mm | ${min['roundel-motto-screen-px']} px |`
    : ''}${
  e.layouts.includes('roundel-name')
    ? `\n| Roundel with the name | ${min['roundel-name-print-mm']} mm | ${min['roundel-name-screen-px']} px |`
    : ''}

Below these the arch fills in and the wordmark stops resolving. The build refuses to emit a raster under the screen minimum — if a size you expected is missing from \`logos/dist/${e.dir}/\`, that is why.

## Files

${built.length ? group(built) : '_Not built yet — run `npm run build:logos`._'}
${shared ? `\n---\n\n${shared}` : ''}`

  mkdirSync(p('logos/guidelines', e.group || '.'), { recursive: true })
  writeFileSync(p('logos/guidelines', `${e.dir}.md`), md)
  console.log(`  ${e.dir.padEnd(34)} ${built.length} files`)
}

writeFileSync(p('logos/guidelines/README.md'), `<!-- GENERATED by tools/build-guidelines.mjs — do not edit. -->

# AJVT marks

Every mark the association owns. Each page is generated from \`brand/entities.yml\`, so it always describes what the build actually produced — not what someone intended a year ago.

| Mark | Kind | Accent | Guidelines |
| --- | --- | --- | --- |
${entities.map((e) => `| ${e.name.ar}<br>${e.name.fr} | ${e.kind}${e.archived ? ' · archived' : ''} | \`${e.accent}\` | [\`${e.id}\`](${e.dir}.md) |`).join('\n')}

## Adding a mark

1. Add an entry to [\`brand/entities.yml\`](../../brand/entities.yml).
2. If it carries a badge, add its glyph to [\`logos/src/glyphs/\`](../src/glyphs/).
3. \`npm run build\`.

You do not draw a logo and you do not write a guidelines page. Both are generated.
`)
console.log('\n  index written')
